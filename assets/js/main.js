const setImageModalState = (isOpen, trigger = null) => {
	if (!imageModal) {
		return;
	}

	if (isOpen && trigger) {
		const image = trigger.querySelector("img");
		const video = trigger.querySelector("video");
		const caption = trigger.querySelector("figcaption");
		if (video && imageVideoPreview) {
			imageVideoPreview.src = video.currentSrc || video.src;
			imageVideoPreview.hidden = false;
			imagePreview.hidden = true;
			imageVideoPreview.play().catch(() => {});
		} else {
			if (imageVideoPreview) {
				imageVideoPreview.hidden = true;
			}
			imagePreview.hidden = false;
			imagePreview.src = image.src;
			imagePreview.alt = image.alt;
		}
		imageCaption.textContent = "";
		imageCaption.append(document.createTextNode(caption.textContent));
		if (trigger.dataset.imageCredit) {
			imageCaption.append(document.createTextNode(" ("));
			const creditLink = document.createElement("a");
			creditLink.href = trigger.dataset.imageCredit;
			creditLink.target = "_blank";
			creditLink.rel = "noopener noreferrer";
			creditLink.textContent = trigger.dataset.imageCreditLabel || "credit";
			imageCaption.append(creditLink);
			imageCaption.append(document.createTextNode(")"));
		} else if (trigger.dataset.imageCreditLabel === "pending") {
			imageCaption.append(document.createTextNode(" ("));
			imageCaption.append(document.createTextNode(translations[activeLanguage].gallery.creditPending));
			imageCaption.append(document.createTextNode(")"));
		}
		imageModal.classList.add("is-open");
		imageModal.setAttribute("aria-hidden", "false");
		imageClose.focus();
		return;
	}

	if (imageVideoPreview) {
		imageVideoPreview.pause();
	}
	imageModal.classList.remove("is-open");
	imageModal.setAttribute("aria-hidden", "true");
};

